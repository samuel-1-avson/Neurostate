//! Timer/Counter Driver Generator
//!
//! Generates timer drivers for various MCU architectures with support for
//! basic counting, input capture, output compare, and one-pulse modes.

use super::templates::*;

/// Generate timer driver code
pub fn generate_timer_driver(config: &TimerConfig, arch: &McuArch, lang: &DriverLanguage) -> DriverOutput {
    match lang {
        DriverLanguage::C => generate_timer_c(config, arch),
        DriverLanguage::Cpp => generate_timer_cpp(config, arch),
        DriverLanguage::Rust => generate_timer_rust(config, arch),
        DriverLanguage::MicroPython => generate_timer_micropython(config, arch),
        DriverLanguage::Zig => generate_timer_zig(config, arch),
        _ => generate_timer_c(config, arch), // Default to C
    }
}

fn generate_timer_c(config: &TimerConfig, _arch: &McuArch) -> DriverOutput {
    let instance = &config.instance;
    let freq = config.frequency_hz;
    
    let mode_str = match config.mode {
        TimerMode::Basic => "BASIC",
        TimerMode::PWM => "PWM",
        TimerMode::InputCapture => "INPUT_CAPTURE",
        TimerMode::OutputCompare => "OUTPUT_COMPARE",
        TimerMode::OnePulse => "ONE_PULSE",
    };

    let header = format!(r#"/**
 * Timer Driver for {instance}
 * Auto-generated by NeuroBench
 * Mode: {mode_str}
 * Frequency: {freq} Hz
 */

#ifndef {instance}_DRIVER_H
#define {instance}_DRIVER_H

#include <stdint.h>
#include <stdbool.h>

// Timer configuration
#define {instance}_FREQUENCY_HZ  {freq}
#define {instance}_MODE          TIMER_MODE_{mode_str}

// Function prototypes
void {instance}_Init(void);
void {instance}_Start(void);
void {instance}_Stop(void);
uint32_t {instance}_GetCounter(void);
void {instance}_SetPeriod(uint32_t period);
void {instance}_RegisterCallback(void (*callback)(void));

#endif // {instance}_DRIVER_H
"#);

    let source = format!(r#"/**
 * Timer Driver for {instance}
 * Auto-generated by NeuroBench
 */

#include "{instance}_driver.h"
#include "stm32f4xx_hal.h"

static TIM_HandleTypeDef h{instance};
static void (*timer_callback)(void) = NULL;

void {instance}_Init(void) {{
    __HAL_RCC_{instance}_CLK_ENABLE();
    
    h{instance}.Instance = {instance};
    h{instance}.Init.Prescaler = (HAL_RCC_GetPCLK1Freq() / {freq}) - 1;
    h{instance}.Init.CounterMode = TIM_COUNTERMODE_UP;
    h{instance}.Init.Period = 1000 - 1;  // 1ms tick
    h{instance}.Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
    h{instance}.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_ENABLE;
    
    HAL_TIM_Base_Init(&h{instance});
}}

void {instance}_Start(void) {{
    HAL_TIM_Base_Start_IT(&h{instance});
}}

void {instance}_Stop(void) {{
    HAL_TIM_Base_Stop_IT(&h{instance});
}}

uint32_t {instance}_GetCounter(void) {{
    return __HAL_TIM_GET_COUNTER(&h{instance});
}}

void {instance}_SetPeriod(uint32_t period) {{
    __HAL_TIM_SET_AUTORELOAD(&h{instance}, period - 1);
}}

void {instance}_RegisterCallback(void (*callback)(void)) {{
    timer_callback = callback;
}}

// IRQ Handler
void {instance}_IRQHandler(void) {{
    if (__HAL_TIM_GET_FLAG(&h{instance}, TIM_FLAG_UPDATE)) {{
        __HAL_TIM_CLEAR_FLAG(&h{instance}, TIM_FLAG_UPDATE);
        if (timer_callback) {{
            timer_callback();
        }}
    }}
}}
"#);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_timer_cpp(config: &TimerConfig, _arch: &McuArch) -> DriverOutput {
    let instance = &config.instance;
    let freq = config.frequency_hz;
    
    let header = format!(r#"/**
 * Timer Driver Class for {instance}
 * Auto-generated by NeuroBench
 */

#pragma once

#include <cstdint>
#include <functional>

class Timer{instance} {{
public:
    enum class Mode {{ Basic, PWM, InputCapture, OutputCompare, OnePulse }};
    
    static void init(uint32_t frequency_hz = {freq});
    static void start();
    static void stop();
    static uint32_t getCounter();
    static void setPeriod(uint32_t period);
    static void setCallback(std::function<void()> callback);
    
private:
    static std::function<void()> callback_;
    static constexpr uint32_t DEFAULT_FREQ = {freq};
}};
"#);

    let source = format!(r#"/**
 * Timer Driver Class Implementation
 * Auto-generated by NeuroBench
 */

#include "Timer{instance}.hpp"
#include "stm32f4xx_hal.h"

std::function<void()> Timer{instance}::callback_;
static TIM_HandleTypeDef htim;

void Timer{instance}::init(uint32_t frequency_hz) {{
    __HAL_RCC_{instance}_CLK_ENABLE();
    
    htim.Instance = {instance};
    htim.Init.Prescaler = (HAL_RCC_GetPCLK1Freq() / frequency_hz) - 1;
    htim.Init.CounterMode = TIM_COUNTERMODE_UP;
    htim.Init.Period = 1000 - 1;
    htim.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_ENABLE;
    
    HAL_TIM_Base_Init(&htim);
}}

void Timer{instance}::start() {{
    HAL_TIM_Base_Start_IT(&htim);
}}

void Timer{instance}::stop() {{
    HAL_TIM_Base_Stop_IT(&htim);
}}

uint32_t Timer{instance}::getCounter() {{
    return __HAL_TIM_GET_COUNTER(&htim);
}}

void Timer{instance}::setPeriod(uint32_t period) {{
    __HAL_TIM_SET_AUTORELOAD(&htim, period - 1);
}}

void Timer{instance}::setCallback(std::function<void()> callback) {{
    callback_ = callback;
}}
"#);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_timer_rust(config: &TimerConfig, _arch: &McuArch) -> DriverOutput {
    let instance = config.instance.to_lowercase();
    let freq = config.frequency_hz;
    
    let source = format!(r#"//! Timer Driver for {instance}
//! Auto-generated by NeuroBench

use embedded_hal::timer::CountDown;
use core::convert::Infallible;

/// Timer wrapper for {instance}
pub struct Timer{instance} {{
    timer: stm32f4xx_hal::timer::Timer<stm32f4xx_hal::pac::{instance}>,
    frequency_hz: u32,
}}

impl Timer{instance} {{
    /// Create new timer
    pub fn new(timer: stm32f4xx_hal::pac::{instance}, clocks: &stm32f4xx_hal::rcc::Clocks) -> Self {{
        let timer = stm32f4xx_hal::timer::Timer::new(timer, clocks);
        Self {{
            timer,
            frequency_hz: {freq},
        }}
    }}
    
    /// Start timer with specified frequency
    pub fn start(&mut self, freq_hz: u32) {{
        self.timer.start(stm32f4xx_hal::time::Hertz::Hz(freq_hz));
    }}
    
    /// Stop timer
    pub fn stop(&mut self) {{
        self.timer.cancel().ok();
    }}
    
    /// Get current counter value
    pub fn counter(&self) -> u32 {{
        self.timer.counter()
    }}
    
    /// Wait for timer update
    pub fn wait(&mut self) -> nb::Result<(), Infallible> {{
        self.timer.wait()
    }}
}}
"#, instance = instance.to_uppercase(), freq = freq);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_timer_micropython(config: &TimerConfig, _arch: &McuArch) -> DriverOutput {
    let instance = &config.instance;
    let freq = config.frequency_hz;
    
    let source = format!(r#"""
Timer Driver for {instance}
Auto-generated by NeuroBench
"""

from machine import Timer
import micropython

class TimerDriver:
    def __init__(self, timer_id=0, frequency={freq}):
        self.timer = Timer(timer_id)
        self.frequency = frequency
        self.callback = None
    
    def start(self, callback=None):
        """Start timer with optional callback"""
        if callback:
            self.callback = callback
        self.timer.init(
            mode=Timer.PERIODIC,
            freq=self.frequency,
            callback=self._irq_handler
        )
    
    def stop(self):
        """Stop timer"""
        self.timer.deinit()
    
    def set_frequency(self, freq):
        """Change timer frequency"""
        self.frequency = freq
        self.stop()
        self.start(self.callback)
    
    @micropython.native
    def _irq_handler(self, timer):
        if self.callback:
            micropython.schedule(self.callback, None)


# Example usage
if __name__ == "__main__":
    def on_tick(arg):
        print("Timer tick!")
    
    timer = TimerDriver(frequency={freq})
    timer.start(callback=on_tick)
"#, instance = instance, freq = freq);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_timer_zig(config: &TimerConfig, _arch: &McuArch) -> DriverOutput {
    let instance = &config.instance;
    let freq = config.frequency_hz;
    
    let source = format!(r#"//! Timer Driver for {instance}
//! Auto-generated by NeuroBench

const std = @import("std");
const hal = @import("hal");

pub const TimerConfig = struct {{
    frequency_hz: u32 = {freq},
    auto_reload: bool = true,
}};

pub const Timer{instance} = struct {{
    const Self = @This();
    
    handle: hal.tim.Handle,
    callback: ?*const fn () void = null,
    
    pub fn init(config: TimerConfig) Self {{
        var handle = hal.tim.init(.{instance}, .{{
            .prescaler = hal.rcc.getPclk1Freq() / config.frequency_hz - 1,
            .counter_mode = .up,
            .period = 1000 - 1,
            .auto_reload_preload = config.auto_reload,
        }});
        
        return Self{{ .handle = handle }};
    }}
    
    pub fn start(self: *Self) void {{
        hal.tim.startIt(self.handle);
    }}
    
    pub fn stop(self: *Self) void {{
        hal.tim.stopIt(self.handle);
    }}
    
    pub fn getCounter(self: *const Self) u32 {{
        return hal.tim.getCounter(self.handle);
    }}
    
    pub fn setPeriod(self: *Self, period: u32) void {{
        hal.tim.setAutoReload(self.handle, period - 1);
    }}
    
    pub fn setCallback(self: *Self, callback: *const fn () void) void {{
        self.callback = callback;
    }}
}};
"#, instance = instance, freq = freq);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

