//! RTC (Real-Time Clock) Driver Generator
//!
//! Generates RTC drivers for timekeeping and alarm functionality.

use super::templates::*;
use serde::{Deserialize, Serialize};

/// RTC configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RtcConfig {
    pub clock_source: RtcClockSource,
    pub enable_alarm: bool,
    pub enable_wakeup: bool,
    pub backup_registers: u8,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum RtcClockSource {
    LSE,    // Low-speed external (32.768 kHz)
    LSI,    // Low-speed internal
    HSE,    // High-speed external divided
}

impl Default for RtcConfig {
    fn default() -> Self {
        Self {
            clock_source: RtcClockSource::LSE,
            enable_alarm: false,
            enable_wakeup: false,
            backup_registers: 0,
        }
    }
}

/// Generate RTC driver code
pub fn generate_rtc_driver(config: &RtcConfig, arch: &McuArch, lang: &DriverLanguage) -> DriverOutput {
    match lang {
        DriverLanguage::C => generate_rtc_c(config, arch),
        DriverLanguage::Cpp => generate_rtc_cpp(config, arch),
        DriverLanguage::Rust => generate_rtc_rust(config, arch),
        DriverLanguage::MicroPython => generate_rtc_micropython(config, arch),
        _ => generate_rtc_c(config, arch),
    }
}

fn generate_rtc_c(config: &RtcConfig, _arch: &McuArch) -> DriverOutput {
    let clock_src = match config.clock_source {
        RtcClockSource::LSE => "RCC_RTCCLKSOURCE_LSE",
        RtcClockSource::LSI => "RCC_RTCCLKSOURCE_LSI",
        RtcClockSource::HSE => "RCC_RTCCLKSOURCE_HSE_DIV32",
    };

    let header = format!(r#"/**
 * RTC Driver
 * Auto-generated by NeuroBench
 */

#ifndef RTC_DRIVER_H
#define RTC_DRIVER_H

#include <stdint.h>
#include <stdbool.h>

// Time structure
typedef struct {{
    uint8_t hours;
    uint8_t minutes;
    uint8_t seconds;
}} RTC_Time_t;

// Date structure
typedef struct {{
    uint8_t weekday;
    uint8_t day;
    uint8_t month;
    uint16_t year;
}} RTC_Date_t;

// Function prototypes
void RTC_Init(void);
void RTC_SetTime(const RTC_Time_t *time);
void RTC_GetTime(RTC_Time_t *time);
void RTC_SetDate(const RTC_Date_t *date);
void RTC_GetDate(RTC_Date_t *date);
uint32_t RTC_GetUnixTimestamp(void);
void RTC_SetUnixTimestamp(uint32_t timestamp);

// Alarm functions
void RTC_SetAlarm(const RTC_Time_t *time, void (*callback)(void));
void RTC_DisableAlarm(void);

// Backup register access
void RTC_WriteBackup(uint8_t index, uint32_t value);
uint32_t RTC_ReadBackup(uint8_t index);

#endif // RTC_DRIVER_H
"#);

    let source = format!(r#"/**
 * RTC Driver Implementation
 * Auto-generated by NeuroBench
 */

#include "rtc_driver.h"
#include "stm32f4xx_hal.h"

static RTC_HandleTypeDef hrtc;
static void (*alarm_callback)(void) = NULL;

void RTC_Init(void) {{
    __HAL_RCC_PWR_CLK_ENABLE();
    HAL_PWR_EnableBkUpAccess();
    
    __HAL_RCC_RTC_CONFIG({clock_src});
    __HAL_RCC_RTC_ENABLE();
    
    hrtc.Instance = RTC;
    hrtc.Init.HourFormat = RTC_HOURFORMAT_24;
    hrtc.Init.AsynchPrediv = 127;
    hrtc.Init.SynchPrediv = 255;
    hrtc.Init.OutPut = RTC_OUTPUT_DISABLE;
    HAL_RTC_Init(&hrtc);
}}

void RTC_SetTime(const RTC_Time_t *time) {{
    RTC_TimeTypeDef sTime = {{0}};
    sTime.Hours = time->hours;
    sTime.Minutes = time->minutes;
    sTime.Seconds = time->seconds;
    HAL_RTC_SetTime(&hrtc, &sTime, RTC_FORMAT_BIN);
}}

void RTC_GetTime(RTC_Time_t *time) {{
    RTC_TimeTypeDef sTime;
    HAL_RTC_GetTime(&hrtc, &sTime, RTC_FORMAT_BIN);
    time->hours = sTime.Hours;
    time->minutes = sTime.Minutes;
    time->seconds = sTime.Seconds;
}}

void RTC_SetDate(const RTC_Date_t *date) {{
    RTC_DateTypeDef sDate = {{0}};
    sDate.WeekDay = date->weekday;
    sDate.Date = date->day;
    sDate.Month = date->month;
    sDate.Year = date->year - 2000;
    HAL_RTC_SetDate(&hrtc, &sDate, RTC_FORMAT_BIN);
}}

void RTC_GetDate(RTC_Date_t *date) {{
    RTC_DateTypeDef sDate;
    HAL_RTC_GetDate(&hrtc, &sDate, RTC_FORMAT_BIN);
    date->weekday = sDate.WeekDay;
    date->day = sDate.Date;
    date->month = sDate.Month;
    date->year = 2000 + sDate.Year;
}}

void RTC_WriteBackup(uint8_t index, uint32_t value) {{
    HAL_RTCEx_BKUPWrite(&hrtc, index, value);
}}

uint32_t RTC_ReadBackup(uint8_t index) {{
    return HAL_RTCEx_BKUPRead(&hrtc, index);
}}
"#, clock_src = clock_src);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_rtc_cpp(config: &RtcConfig, _arch: &McuArch) -> DriverOutput {
    let header = r#"/**
 * RTC Driver Class
 * Auto-generated by NeuroBench
 */

#pragma once
#include <cstdint>
#include <chrono>
#include <functional>

class Rtc {
public:
    struct Time {
        uint8_t hours;
        uint8_t minutes;
        uint8_t seconds;
    };
    
    struct Date {
        uint8_t weekday;
        uint8_t day;
        uint8_t month;
        uint16_t year;
    };
    
    static void init();
    static void setTime(const Time& time);
    static Time getTime();
    static void setDate(const Date& date);
    static Date getDate();
    
    static std::chrono::system_clock::time_point now();
    static void setTimestamp(std::time_t timestamp);
    
    static void setAlarm(const Time& time, std::function<void()> callback);
    static void disableAlarm();
    
    static void writeBackup(uint8_t index, uint32_t value);
    static uint32_t readBackup(uint8_t index);
    
private:
    static std::function<void()> alarm_callback_;
};
"#.to_string();

    let source = r#"/**
 * RTC Driver Class Implementation
 */

#include "Rtc.hpp"
#include "stm32f4xx_hal.h"

std::function<void()> Rtc::alarm_callback_;
static RTC_HandleTypeDef hrtc;

void Rtc::init() {
    __HAL_RCC_PWR_CLK_ENABLE();
    HAL_PWR_EnableBkUpAccess();
    __HAL_RCC_RTC_CONFIG(RCC_RTCCLKSOURCE_LSE);
    __HAL_RCC_RTC_ENABLE();
    
    hrtc.Instance = RTC;
    hrtc.Init.HourFormat = RTC_HOURFORMAT_24;
    hrtc.Init.AsynchPrediv = 127;
    hrtc.Init.SynchPrediv = 255;
    HAL_RTC_Init(&hrtc);
}

Rtc::Time Rtc::getTime() {
    RTC_TimeTypeDef sTime;
    HAL_RTC_GetTime(&hrtc, &sTime, RTC_FORMAT_BIN);
    return {sTime.Hours, sTime.Minutes, sTime.Seconds};
}

void Rtc::setTime(const Time& time) {
    RTC_TimeTypeDef sTime{};
    sTime.Hours = time.hours;
    sTime.Minutes = time.minutes;
    sTime.Seconds = time.seconds;
    HAL_RTC_SetTime(&hrtc, &sTime, RTC_FORMAT_BIN);
}
"#.to_string();

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_rtc_rust(config: &RtcConfig, _arch: &McuArch) -> DriverOutput {
    let source = r#"//! RTC Driver
//! Auto-generated by NeuroBench

use chrono::{DateTime, NaiveDateTime, Utc};

/// RTC time structure
#[derive(Debug, Clone, Copy)]
pub struct RtcTime {
    pub hours: u8,
    pub minutes: u8,
    pub seconds: u8,
}

/// RTC date structure
#[derive(Debug, Clone, Copy)]
pub struct RtcDate {
    pub weekday: u8,
    pub day: u8,
    pub month: u8,
    pub year: u16,
}

/// RTC driver
pub struct RtcDriver {
    rtc: stm32f4xx_hal::rtc::Rtc,
}

impl RtcDriver {
    pub fn new(rtc: stm32f4xx_hal::pac::RTC, pwr: &stm32f4xx_hal::pwr::Pwr) -> Self {
        let rtc = stm32f4xx_hal::rtc::Rtc::new(rtc, pwr);
        Self { rtc }
    }
    
    pub fn get_time(&self) -> RtcTime {
        let time = self.rtc.get_time();
        RtcTime {
            hours: time.hours,
            minutes: time.minutes,
            seconds: time.seconds,
        }
    }
    
    pub fn set_time(&mut self, time: &RtcTime) {
        self.rtc.set_time(&stm32f4xx_hal::rtc::NaiveTime::from_hms(
            time.hours as u32,
            time.minutes as u32,
            time.seconds as u32,
        ));
    }
    
    pub fn get_datetime(&self) -> NaiveDateTime {
        self.rtc.get_datetime()
    }
    
    pub fn set_datetime(&mut self, dt: NaiveDateTime) {
        self.rtc.set_datetime(&dt);
    }
    
    /// Read backup register
    pub fn read_backup(&self, index: u8) -> u32 {
        self.rtc.read_backup_register(index)
    }
    
    /// Write backup register
    pub fn write_backup(&mut self, index: u8, value: u32) {
        self.rtc.write_backup_register(index, value);
    }
}
"#.to_string();

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

