//! Watchdog Timer Driver Generator
//!
//! Generates watchdog timer (IWDG/WWDG) drivers for system monitoring.

use super::templates::*;

/// Watchdog configuration
#[derive(Debug, Clone)]
pub struct WatchdogConfig {
    pub timeout_ms: u32,
    pub window_mode: bool,
    pub window_percent: u8,
}

impl Default for WatchdogConfig {
    fn default() -> Self {
        Self {
            timeout_ms: 1000,
            window_mode: false,
            window_percent: 75,
        }
    }
}

/// Generate watchdog driver code
pub fn generate_watchdog_driver(config: &WatchdogConfig, arch: &McuArch, lang: &DriverLanguage) -> DriverOutput {
    match lang {
        DriverLanguage::C => generate_watchdog_c(config, arch),
        DriverLanguage::Cpp => generate_watchdog_cpp(config, arch),
        DriverLanguage::Rust => generate_watchdog_rust(config, arch),
        DriverLanguage::MicroPython => generate_watchdog_micropython(config, arch),
        DriverLanguage::Zig => generate_watchdog_zig(config, arch),
        _ => generate_watchdog_c(config, arch),
    }
}

fn generate_watchdog_c(config: &WatchdogConfig, _arch: &McuArch) -> DriverOutput {
    let timeout = config.timeout_ms;

    let header = format!(r#"/**
 * Watchdog Timer Driver
 * Auto-generated by NeuroBench
 * Timeout: {timeout}ms
 */

#ifndef WATCHDOG_DRIVER_H
#define WATCHDOG_DRIVER_H

#include <stdint.h>
#include <stdbool.h>

// Watchdog configuration
#define WATCHDOG_TIMEOUT_MS  {timeout}

// Function prototypes
void Watchdog_Init(void);
void Watchdog_Start(void);
void Watchdog_Refresh(void);
void Watchdog_SetTimeout(uint32_t timeout_ms);
bool Watchdog_IsResetByWatchdog(void);

#endif // WATCHDOG_DRIVER_H
"#);

    let source = format!(r#"/**
 * Watchdog Timer Driver Implementation
 * Auto-generated by NeuroBench
 */

#include "watchdog_driver.h"
#include "stm32f4xx_hal.h"

static IWDG_HandleTypeDef hiwdg;

void Watchdog_Init(void) {{
    // IWDG clock is LSI (~32kHz)
    // Timeout = (Prescaler * Reload) / LSI_FREQ
    // For {timeout}ms with prescaler /32:
    // Reload = ({timeout} * 32000) / (32 * 1000) = {timeout}
    
    hiwdg.Instance = IWDG;
    hiwdg.Init.Prescaler = IWDG_PRESCALER_32;
    hiwdg.Init.Reload = ({timeout} * 32000) / (32 * 1000);
    
    if (hiwdg.Init.Reload > 4095) {{
        hiwdg.Init.Reload = 4095;  // Max 12-bit value
    }}
    
    HAL_IWDG_Init(&hiwdg);
}}

void Watchdog_Start(void) {{
    // IWDG starts automatically after init on STM32
    // Just refresh to reset counter
    Watchdog_Refresh();
}}

void Watchdog_Refresh(void) {{
    HAL_IWDG_Refresh(&hiwdg);
}}

void Watchdog_SetTimeout(uint32_t timeout_ms) {{
    // Note: Cannot change timeout once IWDG is started
    // This is for reference only
    hiwdg.Init.Reload = (timeout_ms * 32000) / (32 * 1000);
}}

bool Watchdog_IsResetByWatchdog(void) {{
    return __HAL_RCC_GET_FLAG(RCC_FLAG_IWDGRST) != RESET;
}}
"#);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_watchdog_cpp(config: &WatchdogConfig, _arch: &McuArch) -> DriverOutput {
    let timeout = config.timeout_ms;

    let header = format!(r#"/**
 * Watchdog Timer Driver Class
 * Auto-generated by NeuroBench
 */

#pragma once
#include <cstdint>

class Watchdog {{
public:
    static constexpr uint32_t DEFAULT_TIMEOUT_MS = {timeout};
    
    static void init(uint32_t timeout_ms = DEFAULT_TIMEOUT_MS);
    static void refresh();
    static void start();
    static bool wasReset();
    
    // RAII guard for critical sections
    class Guard {{
    public:
        Guard() {{ Watchdog::refresh(); }}
        ~Guard() {{ Watchdog::refresh(); }}
    }};
}};
"#);

    let source = format!(r#"/**
 * Watchdog Timer Driver Implementation
 */

#include "Watchdog.hpp"
#include "stm32f4xx_hal.h"

static IWDG_HandleTypeDef hiwdg;

void Watchdog::init(uint32_t timeout_ms) {{
    hiwdg.Instance = IWDG;
    hiwdg.Init.Prescaler = IWDG_PRESCALER_32;
    hiwdg.Init.Reload = (timeout_ms * 32000) / (32 * 1000);
    
    if (hiwdg.Init.Reload > 4095) {{
        hiwdg.Init.Reload = 4095;
    }}
    
    HAL_IWDG_Init(&hiwdg);
}}

void Watchdog::refresh() {{
    HAL_IWDG_Refresh(&hiwdg);
}}

void Watchdog::start() {{
    refresh();
}}

bool Watchdog::wasReset() {{
    return __HAL_RCC_GET_FLAG(RCC_FLAG_IWDGRST) != RESET;
}}
"#);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_watchdog_rust(config: &WatchdogConfig, _arch: &McuArch) -> DriverOutput {
    let timeout = config.timeout_ms;

    let source = format!(r#"//! Watchdog Timer Driver
//! Auto-generated by NeuroBench

use embedded_hal::watchdog::{{Watchdog, WatchdogEnable}};

/// Independent Watchdog wrapper
pub struct IwdgDriver {{
    iwdg: stm32f4xx_hal::watchdog::IndependentWatchdog,
    timeout_ms: u32,
}}

impl IwdgDriver {{
    /// Create new watchdog with timeout in milliseconds
    pub fn new(iwdg: stm32f4xx_hal::pac::IWDG) -> Self {{
        let iwdg = stm32f4xx_hal::watchdog::IndependentWatchdog::new(iwdg);
        Self {{
            iwdg,
            timeout_ms: {timeout},
        }}
    }}
    
    /// Start watchdog with configured timeout
    pub fn start(&mut self) {{
        self.iwdg.start(stm32f4xx_hal::time::MilliSeconds(self.timeout_ms));
    }}
    
    /// Feed/refresh the watchdog
    pub fn feed(&mut self) {{
        self.iwdg.feed();
    }}
    
    /// Check if last reset was caused by watchdog
    pub fn was_watchdog_reset() -> bool {{
        // Check RCC flags
        let rcc = unsafe {{ &*stm32f4xx_hal::pac::RCC::ptr() }};
        rcc.csr.read().iwdgrstf().bit_is_set()
    }}
}}

/// RAII guard that feeds watchdog on drop
pub struct WatchdogGuard<'a> {{
    wdg: &'a mut IwdgDriver,
}}

impl<'a> WatchdogGuard<'a> {{
    pub fn new(wdg: &'a mut IwdgDriver) -> Self {{
        wdg.feed();
        Self {{ wdg }}
    }}
}}

impl<'a> Drop for WatchdogGuard<'a> {{
    fn drop(&mut self) {{
        self.wdg.feed();
    }}
}}

pub const DEFAULT_TIMEOUT_MS: u32 = {timeout};
"#, timeout = timeout);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_watchdog_micropython(config: &WatchdogConfig, _arch: &McuArch) -> DriverOutput {
    let timeout = config.timeout_ms;

    let source = format!(r#"""
Watchdog Timer Driver
Auto-generated by NeuroBench
"""

from machine import WDT

class WatchdogDriver:
    def __init__(self, timeout_ms={timeout}):
        self.timeout_ms = timeout_ms
        self.wdt = None
    
    def start(self):
        """Start watchdog timer"""
        # Note: MicroPython WDT cannot be stopped once started
        self.wdt = WDT(timeout=self.timeout_ms)
    
    def feed(self):
        """Feed/refresh watchdog to prevent reset"""
        if self.wdt:
            self.wdt.feed()
    
    def is_started(self):
        """Check if watchdog is running"""
        return self.wdt is not None


class WatchdogGuard:
    """Context manager that feeds watchdog on entry and exit"""
    def __init__(self, wdt):
        self.wdt = wdt
    
    def __enter__(self):
        self.wdt.feed()
        return self
    
    def __exit__(self, *args):
        self.wdt.feed()


# Example usage
if __name__ == "__main__":
    import time
    
    wdt = WatchdogDriver(timeout_ms={timeout})
    wdt.start()
    
    while True:
        # Must feed within timeout
        wdt.feed()
        time.sleep_ms(100)
"#, timeout = timeout);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

fn generate_watchdog_zig(config: &WatchdogConfig, _arch: &McuArch) -> DriverOutput {
    let timeout = config.timeout_ms;

    let source = format!(r#"//! Watchdog Timer Driver
//! Auto-generated by NeuroBench

const hal = @import("hal");

pub const WatchdogConfig = struct {{
    timeout_ms: u32 = {timeout},
}};

pub const Watchdog = struct {{
    const Self = @This();
    
    handle: hal.iwdg.Handle,
    
    pub fn init(config: WatchdogConfig) Self {{
        const reload = (config.timeout_ms * 32000) / (32 * 1000);
        const handle = hal.iwdg.init(.{{
            .prescaler = .div32,
            .reload = @min(reload, 4095),
        }});
        
        return Self{{ .handle = handle }};
    }}
    
    pub fn start(self: *Self) void {{
        self.feed();
    }}
    
    pub fn feed(self: *Self) void {{
        hal.iwdg.refresh(self.handle);
    }}
    
    pub fn wasReset() bool {{
        return hal.rcc.getFlag(.iwdg_rst);
    }}
}};

/// RAII guard for watchdog
pub const WatchdogGuard = struct {{
    wdt: *Watchdog,
    
    pub fn init(wdt: *Watchdog) WatchdogGuard {{
        wdt.feed();
        return WatchdogGuard{{ .wdt = wdt }};
    }}
    
    pub fn deinit(self: WatchdogGuard) void {{
        self.wdt.feed();
    }}
}};
"#, timeout = timeout);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::Timer,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_watchdog_c_generation() {
        let config = WatchdogConfig::default();
        let output = generate_watchdog_driver(&config, &McuArch::ArmCortexM4, &DriverLanguage::C);
        
        assert!(output.header_file.is_some());
        assert!(output.source_file.contains("IWDG"));
    }

    #[test]
    fn test_watchdog_rust_generation() {
        let config = WatchdogConfig { timeout_ms: 2000, ..Default::default() };
        let output = generate_watchdog_driver(&config, &McuArch::ArmCortexM4, &DriverLanguage::Rust);
        
        assert!(output.source_file.contains("2000"));
    }
}
