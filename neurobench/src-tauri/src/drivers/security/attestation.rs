//! Device Attestation Driver
//!
//! Provides remote attestation capabilities for device identity and integrity verification.
//! Supports various attestation protocols including DICE, PSA Attestation, and custom schemes.

use serde::{Deserialize, Serialize};

/// Attestation configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AttestationConfig {
    pub protocol: AttestationProtocol,
    pub device_id: [u8; 16],
    pub use_tpm: bool,
    pub claim_types: Vec<ClaimType>,
}

impl Default for AttestationConfig {
    fn default() -> Self {
        Self {
            protocol: AttestationProtocol::PsaInitialAttestation,
            device_id: [0; 16],
            use_tpm: false,
            claim_types: vec![
                ClaimType::BootState,
                ClaimType::SoftwareVersion,
                ClaimType::HardwareId,
            ],
        }
    }
}

/// Attestation protocol
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AttestationProtocol {
    Dice,                    // Device Identifier Composition Engine
    PsaInitialAttestation,   // ARM PSA
    Tpm2Quote,               // TPM-based attestation
    Custom,
}

/// Claim types for attestation token
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ClaimType {
    BootState,
    SoftwareVersion,
    HardwareId,
    SecurityLifecycle,
    DebugState,
    ClientId,
    ImplementationId,
    ProfileDefinition,
    MeasurementValue,
}

/// DICE layer
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DiceLayer {
    pub code_hash: [u8; 32],
    pub config_hash: [u8; 32],
    pub authority_hash: [u8; 32],
    pub mode: DiceMode,
}

/// DICE operating mode
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum DiceMode {
    NotConfigured,
    Normal,
    Debug,
    Recovery,
}

