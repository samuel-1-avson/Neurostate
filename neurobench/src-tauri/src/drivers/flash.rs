//! Flash Memory Driver Generator
//!
//! Generates internal flash read/write/erase drivers.

use super::templates::*;
use serde::{Deserialize, Serialize};

/// Flash configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FlashConfig {
    pub start_address: u32,
    pub size_kb: u32,
    pub sector_size: u32,
    pub word_size: u8,
}

impl Default for FlashConfig {
    fn default() -> Self {
        Self {
            start_address: 0x0800_0000,
            size_kb: 512,
            sector_size: 16384,
            word_size: 4,
        }
    }
}

/// Generate flash driver code
pub fn generate_flash_driver(config: &FlashConfig, arch: &McuArch, lang: &DriverLanguage) -> DriverOutput {
    match lang {
        DriverLanguage::C => generate_flash_c(config, arch),
        DriverLanguage::Cpp => generate_flash_cpp(config, arch),
        DriverLanguage::Rust => generate_flash_rust(config, arch),
        DriverLanguage::MicroPython => generate_flash_micropython(config, arch),
        _ => generate_flash_c(config, arch),
    }
}

fn generate_flash_c(config: &FlashConfig, _arch: &McuArch) -> DriverOutput {
    let start_addr = config.start_address;
    let size = config.size_kb;
    let sector_size = config.sector_size;

    let header = format!(r#"/**
 * Internal Flash Driver
 * Auto-generated by NeuroBench
 * Flash: 0x{start_addr:08X}, Size: {size}KB
 */

#ifndef FLASH_DRIVER_H
#define FLASH_DRIVER_H

#include <stdint.h>
#include <stdbool.h>

// Flash configuration
#define FLASH_START_ADDRESS  0x{start_addr:08X}UL
#define FLASH_SIZE_KB        {size}
#define FLASH_SECTOR_SIZE    {sector_size}

// Status codes
typedef enum {{
    FLASH_OK = 0,
    FLASH_ERROR_BUSY,
    FLASH_ERROR_PROTECTED,
    FLASH_ERROR_PROGRAM,
    FLASH_ERROR_ERASE,
    FLASH_ERROR_INVALID_ADDR,
}} Flash_Status_t;

// Function prototypes
Flash_Status_t Flash_Unlock(void);
Flash_Status_t Flash_Lock(void);
Flash_Status_t Flash_EraseSector(uint32_t sector);
Flash_Status_t Flash_EraseRange(uint32_t start_addr, uint32_t size);
Flash_Status_t Flash_Write(uint32_t address, const uint8_t *data, uint32_t length);
Flash_Status_t Flash_Read(uint32_t address, uint8_t *data, uint32_t length);
uint32_t Flash_GetSector(uint32_t address);
bool Flash_IsBlank(uint32_t address, uint32_t length);

#endif
"#);

    let source = format!(r#"/**
 * Internal Flash Driver Implementation
 * Auto-generated by NeuroBench
 */

#include "flash_driver.h"
#include "stm32f4xx_hal.h"

Flash_Status_t Flash_Unlock(void) {{
    if (HAL_FLASH_Unlock() != HAL_OK) {{
        return FLASH_ERROR_BUSY;
    }}
    return FLASH_OK;
}}

Flash_Status_t Flash_Lock(void) {{
    if (HAL_FLASH_Lock() != HAL_OK) {{
        return FLASH_ERROR_BUSY;
    }}
    return FLASH_OK;
}}

Flash_Status_t Flash_EraseSector(uint32_t sector) {{
    FLASH_EraseInitTypeDef eraseInit;
    uint32_t sectorError;
    
    eraseInit.TypeErase = FLASH_TYPEERASE_SECTORS;
    eraseInit.VoltageRange = FLASH_VOLTAGE_RANGE_3;
    eraseInit.Sector = sector;
    eraseInit.NbSectors = 1;
    
    Flash_Unlock();
    HAL_StatusTypeDef status = HAL_FLASHEx_Erase(&eraseInit, &sectorError);
    Flash_Lock();
    
    return (status == HAL_OK) ? FLASH_OK : FLASH_ERROR_ERASE;
}}

Flash_Status_t Flash_Write(uint32_t address, const uint8_t *data, uint32_t length) {{
    Flash_Unlock();
    
    for (uint32_t i = 0; i < length; i++) {{
        if (HAL_FLASH_Program(FLASH_TYPEPROGRAM_BYTE, address + i, data[i]) != HAL_OK) {{
            Flash_Lock();
            return FLASH_ERROR_PROGRAM;
        }}
    }}
    
    Flash_Lock();
    return FLASH_OK;
}}

Flash_Status_t Flash_Read(uint32_t address, uint8_t *data, uint32_t length) {{
    for (uint32_t i = 0; i < length; i++) {{
        data[i] = *(__IO uint8_t*)(address + i);
    }}
    return FLASH_OK;
}}

bool Flash_IsBlank(uint32_t address, uint32_t length) {{
    for (uint32_t i = 0; i < length; i++) {{
        if (*(__IO uint8_t*)(address + i) != 0xFF) {{
            return false;
        }}
    }}
    return true;
}}

uint32_t Flash_GetSector(uint32_t address) {{
    // STM32F4 sector mapping
    if (address < 0x08004000) return 0;
    if (address < 0x08008000) return 1;
    if (address < 0x0800C000) return 2;
    if (address < 0x08010000) return 3;
    if (address < 0x08020000) return 4;
    // Add more sectors as needed
    return 5 + ((address - 0x08020000) / 0x20000);
}}
"#);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::DMA, // Using DMA as closest match
    }
}

fn generate_flash_cpp(config: &FlashConfig, _arch: &McuArch) -> DriverOutput {
    let start_addr = config.start_address;
    let size = config.size_kb;

    let header = format!(r#"/**
 * Flash Memory Driver Class
 * Auto-generated by NeuroBench
 */

#pragma once
#include <cstdint>
#include <span>
#include <expected>

class Flash {{
public:
    enum class Error {{
        Ok,
        Busy,
        Protected,
        Program,
        Erase,
        InvalidAddress,
    }};
    
    static constexpr uint32_t START_ADDRESS = 0x{start_addr:08X};
    static constexpr uint32_t SIZE_KB = {size};
    
    static Error unlock();
    static Error lock();
    static Error eraseSector(uint32_t sector);
    static Error write(uint32_t address, std::span<const uint8_t> data);
    static Error read(uint32_t address, std::span<uint8_t> buffer);
    static bool isBlank(uint32_t address, size_t length);
    static uint32_t getSector(uint32_t address);
}};
"#);

    let source = r#"/**
 * Flash Memory Driver Implementation
 */

#include "Flash.hpp"
#include "stm32f4xx_hal.h"

Flash::Error Flash::unlock() {
    return (HAL_FLASH_Unlock() == HAL_OK) ? Error::Ok : Error::Busy;
}

Flash::Error Flash::lock() {
    return (HAL_FLASH_Lock() == HAL_OK) ? Error::Ok : Error::Busy;
}

Flash::Error Flash::write(uint32_t address, std::span<const uint8_t> data) {
    unlock();
    for (size_t i = 0; i < data.size(); ++i) {
        if (HAL_FLASH_Program(FLASH_TYPEPROGRAM_BYTE, address + i, data[i]) != HAL_OK) {
            lock();
            return Error::Program;
        }
    }
    lock();
    return Error::Ok;
}

Flash::Error Flash::read(uint32_t address, std::span<uint8_t> buffer) {
    for (size_t i = 0; i < buffer.size(); ++i) {
        buffer[i] = *reinterpret_cast<volatile uint8_t*>(address + i);
    }
    return Error::Ok;
}
"#.to_string();

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::DMA,
    }
}

fn generate_flash_rust(config: &FlashConfig, _arch: &McuArch) -> DriverOutput {
    let start_addr = config.start_address;
    let size = config.size_kb;

    let source = format!(r#"//! Internal Flash Driver
//! Auto-generated by NeuroBench

use core::ptr;

pub const FLASH_START: u32 = 0x{start_addr:08X};
pub const FLASH_SIZE_KB: u32 = {size};

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum FlashError {{
    Busy,
    Protected,
    Program,
    Erase,
    InvalidAddress,
}}

pub struct FlashDriver {{
    unlocked: bool,
}}

impl FlashDriver {{
    pub fn new() -> Self {{
        Self {{ unlocked: false }}
    }}
    
    pub fn unlock(&mut self) -> Result<(), FlashError> {{
        // Write unlock sequence
        unsafe {{
            let flash = &*stm32f4xx_hal::pac::FLASH::ptr();
            flash.keyr.write(|w| w.bits(0x4567_0123));
            flash.keyr.write(|w| w.bits(0xCDEF_89AB));
        }}
        self.unlocked = true;
        Ok(())
    }}
    
    pub fn lock(&mut self) -> Result<(), FlashError> {{
        unsafe {{
            let flash = &*stm32f4xx_hal::pac::FLASH::ptr();
            flash.cr.modify(|_, w| w.lock().set_bit());
        }}
        self.unlocked = false;
        Ok(())
    }}
    
    pub fn read(&self, address: u32, buffer: &mut [u8]) -> Result<(), FlashError> {{
        if address < FLASH_START {{
            return Err(FlashError::InvalidAddress);
        }}
        
        for (i, byte) in buffer.iter_mut().enumerate() {{
            *byte = unsafe {{ ptr::read_volatile((address + i as u32) as *const u8) }};
        }}
        Ok(())
    }}
    
    pub fn write(&mut self, address: u32, data: &[u8]) -> Result<(), FlashError> {{
        if !self.unlocked {{
            return Err(FlashError::Protected);
        }}
        
        for (i, &byte) in data.iter().enumerate() {{
            unsafe {{
                ptr::write_volatile((address + i as u32) as *mut u8, byte);
            }}
        }}
        Ok(())
    }}
    
    pub fn is_blank(&self, address: u32, length: usize) -> bool {{
        for i in 0..length {{
            let byte = unsafe {{ ptr::read_volatile((address + i as u32) as *const u8) }};
            if byte != 0xFF {{
                return false;
            }}
        }}
        true
    }}
}}
"#, start_addr = start_addr, size = size);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::DMA,
    }
}

fn generate_flash_micropython(config: &FlashConfig, _arch: &McuArch) -> DriverOutput {
    let source = r#""""
Flash Memory Driver
Auto-generated by NeuroBench
"""

import esp32
from micropython import const

# Flash partitions vary by board
_FLASH_START = const(0x00200000)

class FlashDriver:
    """Internal flash read/write driver"""
    
    def __init__(self, partition_name="nvs"):
        try:
            self.partition = esp32.Partition.find(
                esp32.Partition.TYPE_DATA,
                label=partition_name
            )[0]
            self.start = self.partition.info()[2]
            self.size = self.partition.info()[3]
        except:
            self.partition = None
            self.start = 0
            self.size = 0
    
    def read(self, offset, length):
        """Read bytes from flash"""
        if self.partition:
            buf = bytearray(length)
            self.partition.readblocks(offset // 4096, buf)
            return bytes(buf[:length])
        return b''
    
    def write(self, offset, data):
        """Write bytes to flash (must erase first)"""
        if self.partition:
            # Align to block size
            block = offset // 4096
            self.partition.writeblocks(block, data)
            return True
        return False
    
    def erase(self, offset, length):
        """Erase flash region"""
        if self.partition:
            start_block = offset // 4096
            num_blocks = (length + 4095) // 4096
            for i in range(num_blocks):
                self.partition.ioctl(6, start_block + i)  # BLOCK_ERASE
            return True
        return False


# Example usage
if __name__ == "__main__":
    flash = FlashDriver("nvs")
    print(f"Flash: start=0x{flash.start:08X}, size={flash.size}")
"#.to_string();

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::DMA,
    }
}

