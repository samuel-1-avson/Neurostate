//! Matrix Operations for DSP
//!
//! Provides matrix operations optimized for embedded systems.
//! Includes fixed-point and floating-point implementations.

use serde::{Deserialize, Serialize};

/// Matrix configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MatrixConfig {
    pub data_type: MatrixDataType,
    pub use_simd: bool,
    pub use_cmsis: bool,
}

impl Default for MatrixConfig {
    fn default() -> Self {
        Self {
            data_type: MatrixDataType::F32,
            use_simd: true,
            use_cmsis: true,
        }
    }
}

/// Matrix data types
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum MatrixDataType {
    Q15,    // Fixed-point 1.15
    Q31,    // Fixed-point 1.31
    F32,    // Single precision float
    F64,    // Double precision float
}

/// Generate matrix operations driver code
pub fn generate_matrix_driver(config: &MatrixConfig) -> MatrixOutput {
    let dtype_str = format!("{:?}", config.data_type);

    let c_code = format!(r#"/**
 * Matrix Operations Driver
 * Auto-generated by NeuroBench
 * Data Type: {dtype}
 */

#include <stdint.h>
#include <stdbool.h>
#include <string.h>

#ifdef USE_CMSIS_DSP
#include "arm_math.h"
#endif

// Matrix structure
typedef struct {{
    uint16_t rows;
    uint16_t cols;
    float *data;
}} Matrix_f32;

typedef struct {{
    uint16_t rows;
    uint16_t cols;
    int16_t *data;  // Q15 format
}} Matrix_q15;

// Error codes
typedef enum {{
    MATRIX_OK = 0,
    MATRIX_SIZE_MISMATCH,
    MATRIX_SINGULAR,
    MATRIX_NULL_PTR,
}} MatrixResult;

// Function prototypes
void Matrix_Init(Matrix_f32 *mat, uint16_t rows, uint16_t cols, float *data);
MatrixResult Matrix_Add(const Matrix_f32 *a, const Matrix_f32 *b, Matrix_f32 *result);
MatrixResult Matrix_Sub(const Matrix_f32 *a, const Matrix_f32 *b, Matrix_f32 *result);
MatrixResult Matrix_Mult(const Matrix_f32 *a, const Matrix_f32 *b, Matrix_f32 *result);
MatrixResult Matrix_Scale(const Matrix_f32 *a, float scalar, Matrix_f32 *result);
MatrixResult Matrix_Transpose(const Matrix_f32 *a, Matrix_f32 *result);
MatrixResult Matrix_Inverse(const Matrix_f32 *a, Matrix_f32 *result);
float Matrix_Determinant(const Matrix_f32 *a);
void Matrix_Identity(Matrix_f32 *mat);
void Matrix_Zero(Matrix_f32 *mat);

/**
 * Initialize matrix
 */
void Matrix_Init(Matrix_f32 *mat, uint16_t rows, uint16_t cols, float *data) {{
    mat->rows = rows;
    mat->cols = cols;
    mat->data = data;
}}

/**
 * Matrix addition: result = a + b
 */
MatrixResult Matrix_Add(const Matrix_f32 *a, const Matrix_f32 *b, Matrix_f32 *result) {{
    if (a->rows != b->rows || a->cols != b->cols) {{
        return MATRIX_SIZE_MISMATCH;
    }}
    
#ifdef USE_CMSIS_DSP
    arm_matrix_instance_f32 A = {{a->rows, a->cols, a->data}};
    arm_matrix_instance_f32 B = {{b->rows, b->cols, b->data}};
    arm_matrix_instance_f32 R = {{result->rows, result->cols, result->data}};
    arm_mat_add_f32(&A, &B, &R);
#else
    uint32_t n = a->rows * a->cols;
    for (uint32_t i = 0; i < n; i++) {{
        result->data[i] = a->data[i] + b->data[i];
    }}
#endif
    return MATRIX_OK;
}}

/**
 * Matrix multiplication: result = a * b
 */
MatrixResult Matrix_Mult(const Matrix_f32 *a, const Matrix_f32 *b, Matrix_f32 *result) {{
    if (a->cols != b->rows) {{
        return MATRIX_SIZE_MISMATCH;
    }}
    
#ifdef USE_CMSIS_DSP
    arm_matrix_instance_f32 A = {{a->rows, a->cols, a->data}};
    arm_matrix_instance_f32 B = {{b->rows, b->cols, b->data}};
    arm_matrix_instance_f32 R = {{result->rows, result->cols, result->data}};
    arm_mat_mult_f32(&A, &B, &R);
#else
    for (uint16_t i = 0; i < a->rows; i++) {{
        for (uint16_t j = 0; j < b->cols; j++) {{
            float sum = 0.0f;
            for (uint16_t k = 0; k < a->cols; k++) {{
                sum += a->data[i * a->cols + k] * b->data[k * b->cols + j];
            }}
            result->data[i * result->cols + j] = sum;
        }}
    }}
#endif
    return MATRIX_OK;
}}

/**
 * Matrix transpose: result = a^T
 */
MatrixResult Matrix_Transpose(const Matrix_f32 *a, Matrix_f32 *result) {{
#ifdef USE_CMSIS_DSP
    arm_matrix_instance_f32 A = {{a->rows, a->cols, a->data}};
    arm_matrix_instance_f32 R = {{result->rows, result->cols, result->data}};
    arm_mat_trans_f32(&A, &R);
#else
    for (uint16_t i = 0; i < a->rows; i++) {{
        for (uint16_t j = 0; j < a->cols; j++) {{
            result->data[j * result->cols + i] = a->data[i * a->cols + j];
        }}
    }}
#endif
    return MATRIX_OK;
}}

/**
 * Matrix inverse (for small matrices)
 */
MatrixResult Matrix_Inverse(const Matrix_f32 *a, Matrix_f32 *result) {{
    if (a->rows != a->cols) {{
        return MATRIX_SIZE_MISMATCH;
    }}
    
#ifdef USE_CMSIS_DSP
    arm_matrix_instance_f32 A = {{a->rows, a->cols, a->data}};
    arm_matrix_instance_f32 R = {{result->rows, result->cols, result->data}};
    if (arm_mat_inverse_f32(&A, &R) != ARM_MATH_SUCCESS) {{
        return MATRIX_SINGULAR;
    }}
#else
    // Simple Gauss-Jordan for small matrices
    // Full implementation needed for production
#endif
    return MATRIX_OK;
}}

/**
 * Set identity matrix
 */
void Matrix_Identity(Matrix_f32 *mat) {{
    memset(mat->data, 0, mat->rows * mat->cols * sizeof(float));
    for (uint16_t i = 0; i < mat->rows && i < mat->cols; i++) {{
        mat->data[i * mat->cols + i] = 1.0f;
    }}
}}
"#, dtype = dtype_str);

    let rust_code = format!(r#"//! Matrix Operations Driver
//! Auto-generated by NeuroBench

/// Matrix data type
pub const DATA_TYPE: &str = "{dtype}";

/// Matrix errors
#[derive(Debug, Clone)]
pub enum MatrixError {{
    SizeMismatch,
    Singular,
    NullPointer,
}}

pub type MatrixResult<T> = Result<T, MatrixError>;

/// Fixed-size matrix (stack allocated)
#[derive(Debug, Clone)]
pub struct Matrix<const R: usize, const C: usize> {{
    data: [[f32; C]; R],
}}

impl<const R: usize, const C: usize> Matrix<R, C> {{
    /// Create zero matrix
    pub fn zeros() -> Self {{
        Self {{ data: [[0.0; C]; R] }}
    }}
    
    /// Create from array
    pub fn from_array(data: [[f32; C]; R]) -> Self {{
        Self {{ data }}
    }}
    
    /// Get element
    pub fn get(&self, row: usize, col: usize) -> Option<f32> {{
        self.data.get(row).and_then(|r| r.get(col).copied())
    }}
    
    /// Set element
    pub fn set(&mut self, row: usize, col: usize, value: f32) {{
        if let Some(row_data) = self.data.get_mut(row) {{
            if let Some(cell) = row_data.get_mut(col) {{
                *cell = value;
            }}
        }}
    }}
    
    /// Scale matrix
    pub fn scale(&self, scalar: f32) -> Self {{
        let mut result = Self::zeros();
        for i in 0..R {{
            for j in 0..C {{
                result.data[i][j] = self.data[i][j] * scalar;
            }}
        }}
        result
    }}
}}

impl<const N: usize> Matrix<N, N> {{
    /// Create identity matrix
    pub fn identity() -> Self {{
        let mut m = Self::zeros();
        for i in 0..N {{
            m.data[i][i] = 1.0;
        }}
        m
    }}
    
    /// Calculate trace
    pub fn trace(&self) -> f32 {{
        (0..N).map(|i| self.data[i][i]).sum()
    }}
}}

/// Matrix multiplication
pub fn matmul<const M: usize, const N: usize, const P: usize>(
    a: &Matrix<M, N>,
    b: &Matrix<N, P>,
) -> Matrix<M, P> {{
    let mut result = Matrix::<M, P>::zeros();
    for i in 0..M {{
        for j in 0..P {{
            let mut sum = 0.0;
            for k in 0..N {{
                sum += a.data[i][k] * b.data[k][j];
            }}
            result.data[i][j] = sum;
        }}
    }}
    result
}}

/// Matrix addition
pub fn matadd<const R: usize, const C: usize>(
    a: &Matrix<R, C>,
    b: &Matrix<R, C>,
) -> Matrix<R, C> {{
    let mut result = Matrix::<R, C>::zeros();
    for i in 0..R {{
        for j in 0..C {{
            result.data[i][j] = a.data[i][j] + b.data[i][j];
        }}
    }}
    result
}}
"#, dtype = dtype_str);

    MatrixOutput { c_code, rust_code }
}

