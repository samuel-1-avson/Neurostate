//! NFC Driver Generator
//!
//! Generates NFC (Near Field Communication) drivers for contactless communication.
//! Supports NFC-A/B/F/V, card emulation, and peer-to-peer modes.

use serde::{Deserialize, Serialize};

/// NFC configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NfcConfig {
    pub mode: NfcMode,
    pub protocols: Vec<NfcProtocol>,
    pub ndef_enabled: bool,
    pub card_emulation: Option<CardEmulationConfig>,
}

impl Default for NfcConfig {
    fn default() -> Self {
        Self {
            mode: NfcMode::ReaderWriter,
            protocols: vec![NfcProtocol::NfcA, NfcProtocol::NfcB],
            ndef_enabled: true,
            card_emulation: None,
        }
    }
}

/// NFC operating mode
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum NfcMode {
    ReaderWriter,
    CardEmulation,
    PeerToPeer,
}

/// NFC protocols
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum NfcProtocol {
    NfcA,     // ISO 14443-3A (Mifare, NTAG)
    NfcB,     // ISO 14443-3B
    NfcF,     // FeliCa (JIS X 6319-4)
    NfcV,     // ISO 15693 (Vicinity)
    Iso14443, // ISO 14443-4 (ISO-DEP)
    Iso15693, // Long range
}

/// Card emulation configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CardEmulationConfig {
    pub uid: [u8; 7],
    pub atqa: [u8; 2],
    pub sak: u8,
    pub ndef_message: Option<Vec<u8>>,
}

