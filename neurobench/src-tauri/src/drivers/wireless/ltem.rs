//! LTE-M/NB-IoT Cellular Driver Generator
//!
//! Generates drivers for cellular IoT modems (LTE Cat-M1, NB-IoT).
//! Supports common AT command modems like Quectel BG96, uBlox SARA-R4, etc.

use serde::{Deserialize, Serialize};

/// LTE-M configuration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LteMConfig {
    pub modem_type: ModemType,
    pub rat: RadioAccessTech,
    pub apn: String,
    pub bands: Vec<u8>,
    pub psm_enabled: bool,       // Power Saving Mode
    pub edrx_enabled: bool,      // Extended DRX
    pub uart_baud: u32,
}

impl Default for LteMConfig {
    fn default() -> Self {
        Self {
            modem_type: ModemType::QuectelBG96,
            rat: RadioAccessTech::LteCatM1,
            apn: "internet".to_string(),
            bands: vec![2, 4, 12],  // Common US bands
            psm_enabled: true,
            edrx_enabled: false,
            uart_baud: 115200,
        }
    }
}

/// Supported modem types
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ModemType {
    QuectelBG96,
    QuectelBG77,
    UbloxSaraR4,
    SimcomSim7000,
    NordicNRF9160,
}

impl ModemType {
    pub fn manufacturer(&self) -> &'static str {
        match self {
            ModemType::QuectelBG96 | ModemType::QuectelBG77 => "Quectel",
            ModemType::UbloxSaraR4 => "u-blox",
            ModemType::SimcomSim7000 => "SIMCom",
            ModemType::NordicNRF9160 => "Nordic",
        }
    }
}

/// Radio Access Technology
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum RadioAccessTech {
    LteCatM1,
    NbIot,
    LteCatM1NbIot,  // Dual mode
}

