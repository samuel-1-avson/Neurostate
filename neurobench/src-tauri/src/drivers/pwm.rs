//! PWM Driver Generator
//!
//! Generates PWM drivers for various MCU architectures.

use super::templates::*;

/// Generate PWM driver code
pub fn generate_pwm_driver(config: &PwmConfig, arch: &McuArch, lang: &DriverLanguage) -> DriverOutput {
    match lang {
        DriverLanguage::C => generate_pwm_c(config, arch),
        DriverLanguage::Cpp => generate_pwm_cpp(config, arch),
        DriverLanguage::Rust => generate_pwm_rust(config, arch),
        DriverLanguage::MicroPython => generate_pwm_micropython(config, arch),
        DriverLanguage::Zig => generate_pwm_zig(config, arch),
        _ => generate_pwm_c(config, arch),
    }
}

fn generate_pwm_c(config: &PwmConfig, _arch: &McuArch) -> DriverOutput {
    let timer = &config.timer_instance;
    let channel = config.channel;
    let freq = config.frequency_hz;
    let duty = config.duty_cycle_percent;

    let header = format!(r#"/**
 * PWM Driver for {timer} Channel {channel}
 * Auto-generated by NeuroBench
 * Frequency: {freq} Hz, Duty: {duty}%
 */

#ifndef PWM_{timer}_CH{channel}_DRIVER_H
#define PWM_{timer}_CH{channel}_DRIVER_H

#include <stdint.h>

void PWM_{timer}_CH{channel}_Init(void);
void PWM_{timer}_CH{channel}_Start(void);
void PWM_{timer}_CH{channel}_Stop(void);
void PWM_{timer}_CH{channel}_SetDuty(float percent);
void PWM_{timer}_CH{channel}_SetFrequency(uint32_t freq_hz);

#endif
"#);

    let source = format!(r#"/**
 * PWM Driver Implementation
 * Auto-generated by NeuroBench
 */

#include "pwm_{timer}_ch{channel}_driver.h"
#include "stm32f4xx_hal.h"

static TIM_HandleTypeDef htim;
static TIM_OC_InitTypeDef sConfig;
static uint32_t current_period = 0;

void PWM_{timer}_CH{channel}_Init(void) {{
    __HAL_RCC_{timer}_CLK_ENABLE();
    
    uint32_t pclk = HAL_RCC_GetPCLK1Freq();
    uint32_t prescaler = (pclk / ({freq} * 1000)) - 1;
    current_period = 1000 - 1;  // 0.1% resolution
    
    htim.Instance = {timer};
    htim.Init.Prescaler = prescaler;
    htim.Init.CounterMode = TIM_COUNTERMODE_UP;
    htim.Init.Period = current_period;
    htim.Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
    HAL_TIM_PWM_Init(&htim);
    
    sConfig.OCMode = TIM_OCMODE_PWM1;
    sConfig.Pulse = (uint32_t)(current_period * {duty} / 100.0f);
    sConfig.OCPolarity = TIM_OCPOLARITY_HIGH;
    sConfig.OCFastMode = TIM_OCFAST_DISABLE;
    HAL_TIM_PWM_ConfigChannel(&htim, &sConfig, TIM_CHANNEL_{channel});
}}

void PWM_{timer}_CH{channel}_Start(void) {{
    HAL_TIM_PWM_Start(&htim, TIM_CHANNEL_{channel});
}}

void PWM_{timer}_CH{channel}_Stop(void) {{
    HAL_TIM_PWM_Stop(&htim, TIM_CHANNEL_{channel});
}}

void PWM_{timer}_CH{channel}_SetDuty(float percent) {{
    if (percent < 0) percent = 0;
    if (percent > 100) percent = 100;
    
    uint32_t pulse = (uint32_t)(current_period * percent / 100.0f);
    __HAL_TIM_SET_COMPARE(&htim, TIM_CHANNEL_{channel}, pulse);
}}

void PWM_{timer}_CH{channel}_SetFrequency(uint32_t freq_hz) {{
    uint32_t pclk = HAL_RCC_GetPCLK1Freq();
    uint32_t prescaler = (pclk / (freq_hz * 1000)) - 1;
    __HAL_TIM_SET_PRESCALER(&htim, prescaler);
}}
"#);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::PWM,
    }
}

fn generate_pwm_cpp(config: &PwmConfig, _arch: &McuArch) -> DriverOutput {
    let timer = &config.timer_instance;
    let channel = config.channel;
    let freq = config.frequency_hz;
    let duty = config.duty_cycle_percent;

    let header = format!(r#"/**
 * PWM Driver Class
 * Auto-generated by NeuroBench
 */

#pragma once
#include <cstdint>

class Pwm{timer}Ch{channel} {{
public:
    static constexpr uint32_t DEFAULT_FREQ = {freq};
    static constexpr float DEFAULT_DUTY = {duty}f;
    
    static void init(uint32_t freq_hz = DEFAULT_FREQ, float duty = DEFAULT_DUTY);
    static void start();
    static void stop();
    static void setDuty(float percent);
    static void setFrequency(uint32_t freq_hz);
    static float getDuty();
    
private:
    static float current_duty_;
}};
"#);

    let source = format!(r#"/**
 * PWM Driver Class Implementation
 */

#include "Pwm{timer}Ch{channel}.hpp"
#include "stm32f4xx_hal.h"

float Pwm{timer}Ch{channel}::current_duty_ = {duty}f;
static TIM_HandleTypeDef htim;
static uint32_t period = 999;

void Pwm{timer}Ch{channel}::init(uint32_t freq_hz, float duty) {{
    __HAL_RCC_{timer}_CLK_ENABLE();
    
    htim.Instance = {timer};
    htim.Init.Prescaler = (HAL_RCC_GetPCLK1Freq() / (freq_hz * 1000)) - 1;
    htim.Init.Period = period;
    HAL_TIM_PWM_Init(&htim);
    
    TIM_OC_InitTypeDef config{{}};
    config.OCMode = TIM_OCMODE_PWM1;
    config.Pulse = static_cast<uint32_t>(period * duty / 100.0f);
    HAL_TIM_PWM_ConfigChannel(&htim, &config, TIM_CHANNEL_{channel});
    
    current_duty_ = duty;
}}

void Pwm{timer}Ch{channel}::start() {{
    HAL_TIM_PWM_Start(&htim, TIM_CHANNEL_{channel});
}}

void Pwm{timer}Ch{channel}::stop() {{
    HAL_TIM_PWM_Stop(&htim, TIM_CHANNEL_{channel});
}}

void Pwm{timer}Ch{channel}::setDuty(float percent) {{
    percent = (percent < 0) ? 0 : (percent > 100) ? 100 : percent;
    __HAL_TIM_SET_COMPARE(&htim, TIM_CHANNEL_{channel}, 
                          static_cast<uint32_t>(period * percent / 100.0f));
    current_duty_ = percent;
}}

void Pwm{timer}Ch{channel}::setFrequency(uint32_t freq_hz) {{
    __HAL_TIM_SET_PRESCALER(&htim, (HAL_RCC_GetPCLK1Freq() / (freq_hz * 1000)) - 1);
}}

float Pwm{timer}Ch{channel}::getDuty() {{
    return current_duty_;
}}
"#);

    DriverOutput {
        header_file: Some(header),
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::PWM,
    }
}

fn generate_pwm_rust(config: &PwmConfig, _arch: &McuArch) -> DriverOutput {
    let timer = config.timer_instance.to_lowercase();
    let channel = config.channel;
    let freq = config.frequency_hz;
    let duty = config.duty_cycle_percent;

    let source = format!(r#"//! PWM Driver for {timer} Channel {channel}
//! Auto-generated by NeuroBench

use embedded_hal::PwmPin;

/// PWM output on {timer} channel {channel}
pub struct Pwm{timer}Ch{channel}<'a> {{
    pwm: &'a mut dyn PwmPin<Duty = u16>,
    frequency_hz: u32,
}}

impl<'a> Pwm{timer}Ch{channel}<'a> {{
    /// Create new PWM output
    pub fn new(pwm: &'a mut dyn PwmPin<Duty = u16>) -> Self {{
        Self {{
            pwm,
            frequency_hz: {freq},
        }}
    }}
    
    /// Set duty cycle (0.0 - 100.0)
    pub fn set_duty(&mut self, percent: f32) {{
        let percent = percent.clamp(0.0, 100.0);
        let max_duty = self.pwm.get_max_duty();
        let duty = (max_duty as f32 * percent / 100.0) as u16;
        self.pwm.set_duty(duty);
    }}
    
    /// Get current duty cycle
    pub fn duty(&self) -> f32 {{
        let max_duty = self.pwm.get_max_duty();
        let current = self.pwm.get_duty();
        (current as f32 / max_duty as f32) * 100.0
    }}
    
    /// Enable PWM output
    pub fn enable(&mut self) {{
        self.pwm.enable();
    }}
    
    /// Disable PWM output
    pub fn disable(&mut self) {{
        self.pwm.disable();
    }}
}}

/// Default duty cycle: {duty}%
pub const DEFAULT_DUTY: f32 = {duty};
"#, timer = timer.to_uppercase(), channel = channel, freq = freq, duty = duty);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::PWM,
    }
}

fn generate_pwm_micropython(config: &PwmConfig, _arch: &McuArch) -> DriverOutput {
    let channel = config.channel;
    let freq = config.frequency_hz;
    let duty = config.duty_cycle_percent;

    let source = format!(r#"""
PWM Driver
Auto-generated by NeuroBench
"""

from machine import Pin, PWM

class PwmDriver:
    def __init__(self, pin_num, frequency={freq}, duty={duty}):
        self.pin = Pin(pin_num, Pin.OUT)
        self.pwm = PWM(self.pin)
        self.pwm.freq(frequency)
        self.set_duty(duty)
    
    def set_duty(self, percent):
        """Set duty cycle (0-100%)"""
        percent = max(0, min(100, percent))
        # MicroPython uses 0-1023 for duty
        duty_value = int(percent * 1023 / 100)
        self.pwm.duty(duty_value)
    
    def set_frequency(self, freq_hz):
        """Set PWM frequency"""
        self.pwm.freq(freq_hz)
    
    def get_duty(self):
        """Get current duty cycle"""
        return self.pwm.duty() * 100 / 1023
    
    def stop(self):
        """Stop PWM output"""
        self.pwm.deinit()


# Example usage
if __name__ == "__main__":
    pwm = PwmDriver(pin_num=25, frequency={freq}, duty={duty})
    pwm.set_duty(75)  # 75% duty cycle
"#, freq = freq, duty = duty);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::PWM,
    }
}

fn generate_pwm_zig(config: &PwmConfig, _arch: &McuArch) -> DriverOutput {
    let timer = &config.timer_instance;
    let channel = config.channel;
    let freq = config.frequency_hz;
    let duty = config.duty_cycle_percent;

    let source = format!(r#"//! PWM Driver for {timer} Channel {channel}
//! Auto-generated by NeuroBench

const hal = @import("hal");

pub const PwmConfig = struct {{
    frequency_hz: u32 = {freq},
    duty_percent: f32 = {duty},
}};

pub const Pwm{timer}Ch{channel} = struct {{
    const Self = @This();
    
    handle: hal.tim.Handle,
    max_duty: u32,
    
    pub fn init(config: PwmConfig) Self {{
        const period: u32 = 999;
        var handle = hal.tim.pwmInit(.{timer}, .{{
            .prescaler = hal.rcc.getPclk1Freq() / (config.frequency_hz * 1000) - 1,
            .period = period,
        }});
        
        const pulse = @floatToInt(u32, @intToFloat(f32, period) * config.duty_percent / 100.0);
        hal.tim.pwmConfigChannel(handle, .ch{channel}, .{{
            .pulse = pulse,
            .polarity = .high,
        }});
        
        return Self{{ .handle = handle, .max_duty = period }};
    }}
    
    pub fn start(self: *Self) void {{
        hal.tim.pwmStart(self.handle, .ch{channel});
    }}
    
    pub fn stop(self: *Self) void {{
        hal.tim.pwmStop(self.handle, .ch{channel});
    }}
    
    pub fn setDuty(self: *Self, percent: f32) void {{
        const clamped = @max(0.0, @min(100.0, percent));
        const pulse = @floatToInt(u32, @intToFloat(f32, self.max_duty) * clamped / 100.0);
        hal.tim.setCompare(self.handle, .ch{channel}, pulse);
    }}
}};
"#, timer = timer, channel = channel, freq = freq, duty = duty);

    DriverOutput {
        header_file: None,
        source_file: source,
        example_file: None,
        peripheral_type: PeripheralType::PWM,
    }
}

