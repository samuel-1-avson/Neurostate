fn generate_gpio_code(props: &HashMap<String, PropertyValue>, _ctx: &CodeGenContext) -> GeneratedCode {
    let mut code = GeneratedCode::new();
    
    // Extract properties
    let port = prop_str(props, "port", "A");
    let pin = prop_int(props, "pin", 0);
    let mode = prop_enum(props, "mode", "Output");
    let pull = prop_enum(props, "pull", "NoPull");
    
    code.includes.push("<stm32f4xx_hal.h>".to_string());
    
    let pin_name = format!("GPIO_PIN_{}", pin);
    let port_name = format!("GPIO{}", port);
    
    // Define
    code.defines.push(format!("USER_GPIO_PORT {}", port_name));
    code.defines.push(format!("USER_GPIO_PIN {}", pin_name));
    
    // Init code
    let mode_value = match mode.as_str() {
        "Input" => "GPIO_MODE_INPUT",
        "Output" => "GPIO_MODE_OUTPUT_PP",
        "Alternate" => "GPIO_MODE_AF_PP",
        "Analog" => "GPIO_MODE_ANALOG",
        _ => "GPIO_MODE_OUTPUT_PP",
    };
    
    let pull_value = match pull.as_str() {
        "Up" => "GPIO_PULLUP",
        "Down" => "GPIO_PULLDOWN",
        _ => "GPIO_NOPULL",
    };
    
    code.init_code.push(format!(
        "__HAL_{}_CLK_ENABLE();",
        port_name
    ));
    
    code.init_code.push(format!(
        "GPIO_InitTypeDef gpio_init = {{ .Pin = {}, .Mode = {}, .Pull = {}, .Speed = GPIO_SPEED_FREQ_HIGH }};",
        pin_name, mode_value, pull_value
    ));
    
    code.init_code.push(format!(
        "HAL_GPIO_Init({}, &gpio_init);",
        port_name
    ));
    
    code
}

fn generate_adc_code(props: &HashMap<String, PropertyValue>, _ctx: &CodeGenContext) -> GeneratedCode {
    let mut code = GeneratedCode::new();
    
    let channel = prop_int(props, "channel", 0);
    let resolution = prop_int(props, "resolution", 12);
    
    code.includes.push("<stm32f4xx_hal.h>".to_string());
    
    code.globals.push("ADC_HandleTypeDef hadc1;".to_string());
    
    code.init_code.push("__HAL_RCC_ADC1_CLK_ENABLE();".to_string());
    code.init_code.push(format!(
        "hadc1.Instance = ADC1;\nhadc1.Init.ClockPrescaler = ADC_CLOCK_SYNC_PCLK_DIV4;\nhadc1.Init.Resolution = ADC_RESOLUTION_{}_B;\nhadc1.Init.ScanConvMode = DISABLE;\nhadc1.Init.ContinuousConvMode = DISABLE;\nHAL_ADC_Init(&hadc1);",
        resolution
    ));
    
    code.handler_code.push(format!(
        "uint32_t ADC_Read_Channel{}(void) {{\n    ADC_ChannelConfTypeDef cfg = {{ .Channel = ADC_CHANNEL_{}, .Rank = 1, .SamplingTime = ADC_SAMPLETIME_144CYCLES }};\n    HAL_ADC_ConfigChannel(&hadc1, &cfg);\n    HAL_ADC_Start(&hadc1);\n    HAL_ADC_PollForConversion(&hadc1, 100);\n    return HAL_ADC_GetValue(&hadc1);\n}}",
        channel, channel
    ));
    
    code
}

