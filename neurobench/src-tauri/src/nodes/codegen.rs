//! Node Code Generation
//!
//! Generates embedded C/C++ code from node configurations

use super::node_types::*;
use std::collections::HashMap;

/// Code generation context
pub struct CodeGenContext {
    pub target: CodeTarget,
    pub language: CodeLanguage,
    pub hal_framework: HalFramework,
    pub include_comments: bool,
}

impl Default for CodeGenContext {
    fn default() -> Self {
        Self {
            target: CodeTarget::Stm32,
            language: CodeLanguage::C,
            hal_framework: HalFramework::Hal,
            include_comments: true,
        }
    }
}

/// Target MCU family
#[derive(Debug, Clone, Copy)]
pub enum CodeTarget {
    Stm32,
    Esp32,
    Avr,
    Rp2040,
    Generic,
}

/// Output language
#[derive(Debug, Clone, Copy)]
pub enum CodeLanguage {
    C,
    Cpp,
    Rust,
}

/// HAL framework to use
#[derive(Debug, Clone, Copy)]
pub enum HalFramework {
    Hal,      // STM32 HAL
    Ll,       // STM32 LL
    Register, // Direct register
    Arduino,  // Arduino framework
}

/// Generated code with structure
#[derive(Debug, Clone, serde::Serialize)]
pub struct GeneratedCode {
    pub includes: Vec<String>,
    pub defines: Vec<String>,
    pub types: Vec<String>,
    pub globals: Vec<String>,
    pub init_code: Vec<String>,
    pub handler_code: Vec<String>,
    pub main_loop: Vec<String>,
}

impl GeneratedCode {
    pub fn new() -> Self {
        Self {
            includes: Vec::new(),
            defines: Vec::new(),
            types: Vec::new(),
            globals: Vec::new(),
            init_code: Vec::new(),
            handler_code: Vec::new(),
            main_loop: Vec::new(),
        }
    }
    
    /// Merge another generated code into this one
    pub fn merge(&mut self, other: GeneratedCode) {
        self.includes.extend(other.includes);
        self.defines.extend(other.defines);
        self.types.extend(other.types);
        self.globals.extend(other.globals);
        self.init_code.extend(other.init_code);
        self.handler_code.extend(other.handler_code);
        self.main_loop.extend(other.main_loop);
    }
    
    /// Render to complete source file
    pub fn render(&self) -> String {
        let mut output = String::new();
        
        // Includes
        let mut includes: Vec<_> = self.includes.iter().collect();
        includes.sort();
        includes.dedup();
        for inc in includes {
            output.push_str(&format!("#include {}\n", inc));
        }
        output.push('\n');
        
        // Defines
        for def in &self.defines {
            output.push_str(&format!("#define {}\n", def));
        }
        if !self.defines.is_empty() {
            output.push('\n');
        }
        
        // Types
        for typ in &self.types {
            output.push_str(typ);
            output.push_str("\n\n");
        }
        
        // Globals
        for global in &self.globals {
            output.push_str(global);
            output.push('\n');
        }
        if !self.globals.is_empty() {
            output.push('\n');
        }
        
        // Handler functions
        for handler in &self.handler_code {
            output.push_str(handler);
            output.push_str("\n\n");
        }
        
        // Init function
        output.push_str("void System_Init(void) {\n");
        for init in &self.init_code {
            output.push_str("    ");
            output.push_str(init);
            output.push('\n');
        }
        output.push_str("}\n\n");
        
        // Main loop
        output.push_str("void System_Update(void) {\n");
        for main in &self.main_loop {
            output.push_str("    ");
            output.push_str(main);
            output.push('\n');
        }
        output.push_str("}\n");
        
        output
    }
    
    /// Render to multiple files for project structure
    pub fn render_multi_file(&self) -> Vec<CodeFile> {
        let mut files = Vec::new();
        
        // 1. hal_config.h - Hardware configuration header
        let mut hal_h = String::new();
        hal_h.push_str("/**\n * hal_config.h\n * Generated by NeuroBench\n */\n\n");
        hal_h.push_str("#ifndef HAL_CONFIG_H\n#define HAL_CONFIG_H\n\n");
        
        // Includes
        let mut includes: Vec<_> = self.includes.iter().collect();
        includes.sort();
        includes.dedup();
        for inc in includes {
            hal_h.push_str(&format!("#include {}\n", inc));
        }
        hal_h.push('\n');
        
        // Defines
        for def in &self.defines {
            hal_h.push_str(&format!("#define {}\n", def));
        }
        hal_h.push('\n');
        
        // Types
        for typ in &self.types {
            hal_h.push_str(typ);
            hal_h.push_str("\n\n");
        }
        
        // Extern declarations for globals
        for global in &self.globals {
            if global.contains("=") {
                let decl = global.split('=').next().unwrap_or(global);
                hal_h.push_str(&format!("extern {};\n", decl.trim()));
            } else {
                hal_h.push_str(&format!("extern {};\n", global.trim_end_matches(';')));
            }
        }
        hal_h.push('\n');
        
        // Function prototypes
        hal_h.push_str("// System functions\n");
        hal_h.push_str("void System_Init(void);\n");
        hal_h.push_str("void System_Update(void);\n\n");
        
        hal_h.push_str("#endif // HAL_CONFIG_H\n");
        
        files.push(CodeFile {
            name: "hal_config.h".to_string(),
            content: hal_h,
            language: "c".to_string(),
        });
        
        // 2. hal_config.c - Hardware implementation
        let mut hal_c = String::new();
        hal_c.push_str("/**\n * hal_config.c\n * Generated by NeuroBench\n */\n\n");
        hal_c.push_str("#include \"hal_config.h\"\n\n");
        
        // Global variables
        for global in &self.globals {
            hal_c.push_str(global);
            hal_c.push('\n');
        }
        hal_c.push('\n');
        
        // Init function
        hal_c.push_str("void System_Init(void) {\n");
        for init in &self.init_code {
            hal_c.push_str("    ");
            hal_c.push_str(init);
            hal_c.push('\n');
        }
        hal_c.push_str("}\n\n");
        
        // Update function
        hal_c.push_str("void System_Update(void) {\n");
        for main in &self.main_loop {
            hal_c.push_str("    ");
            hal_c.push_str(main);
            hal_c.push('\n');
        }
        hal_c.push_str("}\n");
        
        files.push(CodeFile {
            name: "hal_config.c".to_string(),
            content: hal_c,
            language: "c".to_string(),
        });
        
        // 3. handlers.c - Interrupt and callback handlers
        if !self.handler_code.is_empty() {
            let mut handlers_c = String::new();
            handlers_c.push_str("/**\n * handlers.c\n * Interrupt and callback handlers\n * Generated by NeuroBench\n */\n\n");
            handlers_c.push_str("#include \"hal_config.h\"\n\n");
            
            for handler in &self.handler_code {
                handlers_c.push_str(handler);
                handlers_c.push_str("\n\n");
            }
            
            files.push(CodeFile {
                name: "handlers.c".to_string(),
                content: handlers_c,
                language: "c".to_string(),
            });
        }
        
        // 4. main.c - Application entry point
        let mut main_c = String::new();
        main_c.push_str("/**\n * main.c\n * Application entry point\n * Generated by NeuroBench\n */\n\n");
        main_c.push_str("#include \"hal_config.h\"\n\n");
        main_c.push_str("int main(void) {\n");
        main_c.push_str("    // Initialize HAL\n");
        main_c.push_str("    HAL_Init();\n\n");
        main_c.push_str("    // Initialize peripherals\n");
        main_c.push_str("    System_Init();\n\n");
        main_c.push_str("    // Main loop\n");
        main_c.push_str("    while (1) {\n");
        main_c.push_str("        System_Update();\n");
        main_c.push_str("    }\n");
        main_c.push_str("}\n");
        
        files.push(CodeFile {
            name: "main.c".to_string(),
            content: main_c,
            language: "c".to_string(),
        });
        
        files
    }
}

/// A single code file for multi-file export
#[derive(Debug, Clone, serde::Serialize)]
pub struct CodeFile {
    pub name: String,
    pub content: String,
    pub language: String,
}

impl Default for GeneratedCode {
    fn default() -> Self {
        Self::new()
    }
}

/// Generate code for a specific node type with properties
pub fn generate_node_code(
    node_type: &NodeType,
    properties: &HashMap<String, PropertyValue>,
    ctx: &CodeGenContext,
) -> GeneratedCode {
    match node_type {
        // ===== Hardware Nodes =====
        NodeType::Gpio => generate_gpio_code(properties, ctx),
        NodeType::Adc => generate_adc_code(properties, ctx),
        NodeType::Dac => generate_dac_code(properties, ctx),
        NodeType::Pwm => generate_pwm_code(properties, ctx),
        NodeType::Uart => generate_uart_code(properties, ctx),
        NodeType::Spi => generate_spi_code(properties, ctx),
        NodeType::I2c => generate_i2c_code(properties, ctx),
        NodeType::Timer => generate_timer_code(properties, ctx),
        
        // ===== Control/RTOS Nodes =====
        NodeType::Task => generate_task_code(properties, ctx),
        NodeType::Semaphore => generate_semaphore_code(properties, ctx),
        NodeType::Mutex => generate_mutex_code(properties, ctx),
        NodeType::Queue => generate_queue_code(properties, ctx),
        NodeType::Interrupt => generate_interrupt_code(properties, ctx),
        
        // ===== I/O Nodes =====
        NodeType::Led => generate_led_code(properties, ctx),
        NodeType::Button => generate_button_code(properties, ctx),
        NodeType::Motor => generate_motor_code(properties, ctx),
        
        // ===== FSM Nodes =====
        NodeType::State | NodeType::Initial | NodeType::Final => 
            generate_state_code(node_type, properties, ctx),
        
        // Default - empty code
        _ => GeneratedCode::new(),
    }
}

