fn generate_interrupt_code(props: &HashMap<String, PropertyValue>, _ctx: &CodeGenContext) -> GeneratedCode {
    let mut code = GeneratedCode::new();
    
    let irq = prop_str(props, "irq_name", "EXTI0");
    let priority = prop_int(props, "priority", 5);
    let pin = prop_int(props, "pin", 0);
    
    code.includes.push("<stm32f4xx_hal.h>".to_string());
    
    // Add volatile flag for ISR-to-task communication
    code.globals.push(format!("volatile uint8_t {}_flag = 0;", irq.to_lowercase()));
    
    code.init_code.push(format!(
        "HAL_NVIC_SetPriority({}_IRQn, {}, 0);\nHAL_NVIC_EnableIRQ({}_IRQn);",
        irq, priority, irq
    ));
    
    // Real interrupt handler with flag clearing and debounce
    code.handler_code.push(format!(
        "void {}_IRQHandler(void) {{\n\
    // Check pending interrupt\n\
    if (__HAL_GPIO_EXTI_GET_IT(GPIO_PIN_{}) != RESET) {{\n\
        __HAL_GPIO_EXTI_CLEAR_IT(GPIO_PIN_{});\n\n\
        // Set flag for main loop / task processing\n\
        {}_flag = 1;\n\n\
        // For RTOS: Signal task from ISR\n\
        // BaseType_t xHigherPriorityTaskWoken = pdFALSE;\n\
        // xSemaphoreGiveFromISR(exti_sem, &xHigherPriorityTaskWoken);\n\
        // portYIELD_FROM_ISR(xHigherPriorityTaskWoken);\n\
    }}\n}}",
        irq, pin, pin, irq.to_lowercase()
    ));
    
    code
}

