// ============================================================================
// Property Helpers
// ============================================================================

fn prop_str(props: &HashMap<String, PropertyValue>, key: &str, default: &str) -> String {
    match props.get(key) {
        Some(PropertyValue::String(s)) => s.clone(),
        _ => default.to_string(),
    }
}

fn prop_int(props: &HashMap<String, PropertyValue>, key: &str, default: i64) -> i64 {
    match props.get(key) {
        Some(PropertyValue::Integer(n)) => *n,
        _ => default,
    }
}

fn prop_bool(props: &HashMap<String, PropertyValue>, key: &str, default: bool) -> bool {
    match props.get(key) {
        Some(PropertyValue::Boolean(b)) => *b,
        _ => default,
    }
}

fn prop_enum(props: &HashMap<String, PropertyValue>, key: &str, default: &str) -> String {
    match props.get(key) {
        Some(PropertyValue::Enum { value, .. }) => value.clone(),
        _ => default.to_string(),
    }
}

