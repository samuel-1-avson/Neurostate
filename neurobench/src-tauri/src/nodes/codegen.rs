fn generate_led_code(props: &HashMap<String, PropertyValue>, ctx: &CodeGenContext) -> GeneratedCode {
    // LED is essentially GPIO output
    let mut mod_props = props.clone();
    mod_props.insert("mode".to_string(), PropertyValue::String("Output".to_string()));
    
    let mut code = generate_gpio_code(&mod_props, ctx);
    
    let port = prop_str(props, "port", "A");
    let pin = prop_int(props, "pin", 0);
    
    code.handler_code.push(format!(
        "void LED_{}_{}_On(void) {{ HAL_GPIO_WritePin(GPIO{}, GPIO_PIN_{}, GPIO_PIN_SET); }}\nvoid LED_{}_{}_Off(void) {{ HAL_GPIO_WritePin(GPIO{}, GPIO_PIN_{}, GPIO_PIN_RESET); }}\nvoid LED_{}_{}_Toggle(void) {{ HAL_GPIO_TogglePin(GPIO{}, GPIO_PIN_{}); }}",
        port, pin, port, pin, port, pin, port, pin, port, pin, port, pin
    ));
    
    code
}

fn generate_button_code(props: &HashMap<String, PropertyValue>, ctx: &CodeGenContext) -> GeneratedCode {
    let mut mod_props = props.clone();
    mod_props.insert("mode".to_string(), PropertyValue::String("Input".to_string()));
    
    let mut code = generate_gpio_code(&mod_props, ctx);
    
    let port = prop_str(props, "port", "A");
    let pin = prop_int(props, "pin", 0);
    let active_low = prop_bool(props, "active_low", false);
    
    let compare = if active_low { "GPIO_PIN_RESET" } else { "GPIO_PIN_SET" };
    
    code.handler_code.push(format!(
        "uint8_t Button_{}_{}_IsPressed(void) {{ return HAL_GPIO_ReadPin(GPIO{}, GPIO_PIN_{}) == {}; }}",
        port, pin, port, pin, compare
    ));
    
    code
}

fn generate_motor_code(props: &HashMap<String, PropertyValue>, _ctx: &CodeGenContext) -> GeneratedCode {
    let mut code = GeneratedCode::new();
    
    let name = prop_str(props, "name", "motor1");
    let timer = prop_int(props, "timer", 1);
    let channel = prop_int(props, "channel", 1);
    let dir_port = prop_str(props, "dir_port", "B");
    let dir_pin = prop_int(props, "dir_pin", 0);
    
    code.includes.push("<stm32f4xx_hal.h>".to_string());
    
    // Motor control defines
    code.defines.push(format!("{}_DIR_PORT GPIO{}", name.to_uppercase(), dir_port));
    code.defines.push(format!("{}_DIR_PIN GPIO_PIN_{}", name.to_uppercase(), dir_pin));
    code.defines.push(format!("{}_TIM htim{}", name.to_uppercase(), timer));
    code.defines.push(format!("{}_CHANNEL TIM_CHANNEL_{}", name.to_uppercase(), channel));
    
    // Motor control function with direction and speed
    code.handler_code.push(format!(
        "/**\n\
 * Set motor speed and direction\n\
 * @param speed: -100 to +100 percent (negative = reverse)\n\
 */\n\
void {}_SetSpeed(int16_t speed) {{\n\
    // Clamp speed to valid range\n\
    if (speed > 100) speed = 100;\n\
    if (speed < -100) speed = -100;\n\n\
    // Set direction via H-bridge control pin\n\
    if (speed >= 0) {{\n\
        HAL_GPIO_WritePin({}_DIR_PORT, {}_DIR_PIN, GPIO_PIN_SET);\n\
    }} else {{\n\
        HAL_GPIO_WritePin({}_DIR_PORT, {}_DIR_PIN, GPIO_PIN_RESET);\n\
        speed = -speed; // Use absolute value for duty\n\
    }}\n\n\
    // Map 0-100% to PWM range (0-999 for 1kHz PWM with period 999)\n\
    uint16_t duty = (uint16_t)((speed * 999) / 100);\n\
    __HAL_TIM_SET_COMPARE(&{}_TIM, {}_CHANNEL, duty);\n}}",
        name, 
        name.to_uppercase(), name.to_uppercase(),
        name.to_uppercase(), name.to_uppercase(),
        name.to_uppercase(), name.to_uppercase()
    ));
    
    // Brake function
    code.handler_code.push(format!(
        "/**\n\
 * Stop motor (set PWM to 0)\n\
 */\n\
void {}_Stop(void) {{\n\
    __HAL_TIM_SET_COMPARE(&{}_TIM, {}_CHANNEL, 0);\n}}",
        name, name.to_uppercase(), name.to_uppercase()
    ));
    
    code
}

