fn generate_task_code(props: &HashMap<String, PropertyValue>, _ctx: &CodeGenContext) -> GeneratedCode {
    let mut code = GeneratedCode::new();
    
    let name = prop_str(props, "name", "DefaultTask");
    let priority = prop_int(props, "priority", 1);
    let stack = prop_int(props, "stack_size", 256);
    let period_ms = prop_int(props, "period_ms", 100);
    
    code.includes.push("<FreeRTOS.h>".to_string());
    code.includes.push("<task.h>".to_string());
    
    code.globals.push(format!("TaskHandle_t {}Handle;", name));
    
    // Real task implementation with proper timing
    code.handler_code.push(format!(
        "void {}(void *argument) {{\n\
    TickType_t xLastWakeTime = xTaskGetTickCount();\n\
    const TickType_t xFrequency = pdMS_TO_TICKS({});\n\n\
    for(;;) {{\n\
        // ===== Task Logic Start =====\n\
        // Read inputs, process data, update outputs\n\
        // Example: uint32_t sensor_val = ADC_Read();\n\
        // Example: FSM_Process(sensor_val);\n\
        // ===== Task Logic End =====\n\n\
        // Precise periodic timing (better than vTaskDelay)\n\
        vTaskDelayUntil(&xLastWakeTime, xFrequency);\n\
    }}\n}}",
        name, period_ms
    ));
    
    code.init_code.push(format!(
        "xTaskCreate({}, \"{}\", {}, NULL, {}, &{}Handle);",
        name, name, stack, priority, name
    ));
    
    code
}

fn generate_semaphore_code(props: &HashMap<String, PropertyValue>, _ctx: &CodeGenContext) -> GeneratedCode {
    let mut code = GeneratedCode::new();
    
    let name = prop_str(props, "name", "sem");
    let sem_type = prop_enum(props, "type", "Binary");
    let initial = prop_int(props, "initial_count", 0);
    
    code.includes.push("<FreeRTOS.h>".to_string());
    code.includes.push("<semphr.h>".to_string());
    
    code.globals.push(format!("SemaphoreHandle_t {};", name));
    
    match sem_type.as_str() {
        "Counting" => {
            let max = prop_int(props, "max_count", 10);
            code.init_code.push(format!(
                "{} = xSemaphoreCreateCounting({}, {});",
                name, max, initial
            ));
        }
        _ => {
            code.init_code.push(format!(
                "{} = xSemaphoreCreateBinary();",
                name
            ));
            if initial > 0 {
                code.init_code.push(format!("xSemaphoreGive({});", name));
            }
        }
    }
    
    code
}

