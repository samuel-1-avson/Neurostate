fn generate_pwm_code(props: &HashMap<String, PropertyValue>, _ctx: &CodeGenContext) -> GeneratedCode {
    let mut code = GeneratedCode::new();
    
    let timer = prop_int(props, "timer", 1);
    let channel = prop_int(props, "channel", 1);
    let frequency = prop_int(props, "frequency", 1000);
    
    code.includes.push("<stm32f4xx_hal.h>".to_string());
    code.globals.push(format!("TIM_HandleTypeDef htim{};", timer));
    
    let prescaler = 84000000 / (frequency * 1000) - 1;
    
    code.init_code.push(format!(
        "__HAL_RCC_TIM{}_CLK_ENABLE();\nhtim{}.Instance = TIM{};\nhtim{}.Init.Prescaler = {};\nhtim{}.Init.Period = 999;\nhtim{}.Init.CounterMode = TIM_COUNTERMODE_UP;\nHAL_TIM_PWM_Init(&htim{});",
        timer, timer, timer, timer, prescaler, timer, timer, timer
    ));
    
    code.init_code.push(format!(
        "TIM_OC_InitTypeDef oc = {{ .OCMode = TIM_OCMODE_PWM1, .Pulse = 500 }};\nHAL_TIM_PWM_ConfigChannel(&htim{}, &oc, TIM_CHANNEL_{});\nHAL_TIM_PWM_Start(&htim{}, TIM_CHANNEL_{});",
        timer, channel, timer, channel
    ));
    
    code.handler_code.push(format!(
        "void PWM_SetDuty_Tim{}Ch{}(uint16_t duty) {{\n    __HAL_TIM_SET_COMPARE(&htim{}, TIM_CHANNEL_{}, duty);\n}}",
        timer, channel, timer, channel
    ));
    
    code
}

